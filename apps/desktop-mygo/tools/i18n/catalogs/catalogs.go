// Package catalogs 把原版前端的 i18next 语言包（apps/desktop/frontend/src/locales/<语言>.json）
// 转换成 MyGo 的 ARB 目录（ui/locales/<语言>.json），两个前端共用同一份翻译。
//
// 转换规则：
//   - 嵌套的 key 用 _ 连起来：library.toast.batchStatusUpdated → library_toast_batchStatusUpdated，
//     MyGo 生成的 Go 函数是 locales.LibraryToastBatchStatusUpdated(count, status string)。
//   - i18next 的 {{name}} 写成 ICU 的 {name}，参数一律是 String：i18next 原样插入值，
//     MyGo 的数字参数会按语言加千分位（Steam AppID 会变成 1,144,400），所以由调用方自己格式化。
//   - ICU 里单引号与花括号有特殊含义：单引号一律写成两个，字面的 { } 用单引号括起来。
//   - zh-CN（原版的 fallbackLng）是源语言：它的目录有全部消息，并在 @key 里记下原版的 key 与参数。
//     其他语言缺的消息回退到 zh-CN；源语言没有的 key、源语言没有的参数会被丢弃并报告。
//
// extra 目录是 desktop-mygo 自己的补充消息，同样是嵌套的 JSON：原版没有的文字放在 native 下；
// 顶层的 mygo 对象是 MyGo 自带文字（mygo.undo 等，MyGo 没有翻译的语言如 ja-JP）的翻译，key 保留点号，
// 消息已经是 ICU（MyGo 的消息要用 plural），不做转换。
package catalogs

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strings"
)

// Source 是源语言，与原版 i18n.ts 的 fallbackLng 相同。
const Source = "zh-CN"

// Languages 是原版支持的语言（i18n.ts 的 resources，也是配置 language 的取值），源语言在前。
var Languages = []string{"zh-CN", "zh-TW", "en-US", "ja-JP"}

// Renames 是拍平后与别的 key 生成同名 Go 函数的原版 key 的新名字（MyGo 的函数名去掉 _ 并把每段首字母大写，
// idPreviewLoading 与 idPreview.loading 都是 IdPreviewLoading）。转换时报冲突就在这里加一条。
var Renames = map[string]string{
	"settings.metadata.idPreview.loading": "settings_metadata_idPreview_loadingText",
}

// Options 是转换的输入目录。
type Options struct {
	Frontend string // apps/desktop/frontend/src/locales
	Extra    string // apps/desktop-mygo/tools/i18n/extra
}

// Result 是转换结果：每种语言一个 ARB 文件的内容，以及转换时丢弃或无法转换的条目。
type Result struct {
	Files    map[string][]byte // 文件名（zh-CN.json）→ 内容
	Warnings []string
}

// message 是一条拍平后的消息。
type message struct {
	key    string // ARB 的 key（library_toast_batchStatusUpdated，或 mygo.undo）
	origin string // 原版的 key（library.toast.batchStatusUpdated），extra 里的消息带 extra: 前缀
	text   string // ICU 消息
	params []string
}

// Convert 读取原版与补充的语言包，转换成 MyGo 的目录。
func Convert(opts Options) (*Result, error) {
	res := &Result{Files: map[string][]byte{}}
	byLang := map[string][]message{}
	for _, lang := range Languages {
		msgs, err := readLocale(filepath.Join(opts.Frontend, lang+".json"), "", res)
		if err != nil {
			return nil, err
		}
		extraPath := filepath.Join(opts.Extra, lang+".json")
		if _, err := os.Stat(extraPath); err == nil {
			extra, err := readLocale(extraPath, "extra:", res)
			if err != nil {
				return nil, err
			}
			seen := map[string]bool{}
			for _, m := range msgs {
				seen[m.key] = true
			}
			for _, m := range extra {
				if seen[m.key] {
					return nil, fmt.Errorf("%s：%s 与原版的 key 重名", extraPath, m.origin)
				}
			}
			msgs = append(msgs, extra...)
		}
		byLang[lang] = msgs
	}

	source := map[string]message{}
	for _, m := range byLang[Source] {
		source[m.key] = m
	}
	for _, lang := range Languages {
		var kept []message
		for _, m := range byLang[lang] {
			if lang != Source && !strings.HasPrefix(m.key, "mygo.") {
				src, ok := source[m.key]
				if !ok {
					res.Warnings = append(res.Warnings, fmt.Sprintf("%s：%s 在源语言 %s 里没有，已丢弃", lang, m.origin, Source))
					continue
				}
				if extra := missing(m.params, src.params); len(extra) > 0 {
					res.Warnings = append(res.Warnings, fmt.Sprintf("%s：%s 用了源语言没有的参数 %v，已丢弃（回退到 %s）", lang, m.origin, extra, Source))
					continue
				}
			}
			kept = append(kept, m)
		}
		res.Files[lang+".json"] = encode(lang, kept, lang == Source)
	}
	res.Files[RenamesFile] = renamesGo()
	return res, nil
}

// RenamesFile 是写进 ui/locales 的 Renames，locales.Key 按原版 key 查消息时用。
const RenamesFile = "renames_gen.go"

func renamesGo() []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/i18n. DO NOT EDIT.\n\npackage locales\n\n")
	b.WriteString("// renames 是 tools/i18n/catalogs.Renames：拍平后会与别的 key 重名的原版 key 的新名字。\n")
	b.WriteString("var renames = map[string]string{\n")
	keys := make([]string, 0, len(Renames))
	for k := range Renames {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(&b, "\t%q: %q,\n", k, Renames[k])
	}
	b.WriteString("}\n")
	return b.Bytes()
}

// readLocale 读取一个嵌套的 i18next 语言包，按文件中的顺序拍平。
func readLocale(path, originPrefix string, res *Result) ([]message, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	var msgs []message
	var walk func(prefix []string) error
	walk = func(prefix []string) error {
		tok, err := dec.Token()
		if err != nil {
			return err
		}
		switch v := tok.(type) {
		case json.Delim:
			if v != '{' {
				return fmt.Errorf("%s：%s 不是字符串或对象", path, strings.Join(prefix, "."))
			}
			for dec.More() {
				kt, err := dec.Token()
				if err != nil {
					return err
				}
				if err := walk(append(slices.Clone(prefix), kt.(string))); err != nil {
					return err
				}
			}
			_, err := dec.Token() // }
			return err
		case string:
			origin := strings.Join(prefix, ".")
			key := ARBKey(origin)
			if len(prefix) > 1 && prefix[0] == "mygo" {
				key = "mygo." + strings.Join(prefix[1:], "_")
			}
			if !keyPattern.MatchString(strings.TrimPrefix(key, "mygo.")) {
				return fmt.Errorf("%s：%s 不能作为 MyGo 的 key（只能是字母开头的字母、数字）", path, origin)
			}
			if strings.HasPrefix(key, "mygo.") {
				// MyGo 自带文字的翻译直接写成 ICU（要用 plural），原样保留。
				msgs = append(msgs, message{key: key, origin: originPrefix + origin, text: v})
				return nil
			}
			text, params, err := toICU(v)
			if err != nil {
				res.Warnings = append(res.Warnings, fmt.Sprintf("%s：%s：%v，已丢弃", path, origin, err))
				return nil
			}
			msgs = append(msgs, message{key: key, origin: originPrefix + origin, text: text, params: params})
			return nil
		default:
			return fmt.Errorf("%s：%s 不是字符串或对象", path, strings.Join(prefix, "."))
		}
	}
	if err := walk(nil); err != nil {
		return nil, fmt.Errorf("读取 %s：%w", path, err)
	}
	return msgs, nil
}

// ARBKey 返回原版 key 在 MyGo 目录里的 key：点号换成 _，或 Renames 里的新名字。
func ARBKey(origin string) string {
	if k, ok := Renames[origin]; ok {
		return k
	}
	return strings.ReplaceAll(origin, ".", "_")
}

var (
	keyPattern  = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9_]*$`)
	placeholder = regexp.MustCompile(`^\{\{\s*([A-Za-z_][A-Za-z0-9_]*)\s*\}\}`)
)

// toICU 把 i18next 的消息写成 ICU MessageFormat，返回其中的参数（按出现顺序，不重复）。
func toICU(s string) (string, []string, error) {
	if strings.Contains(s, "$t(") {
		return "", nil, fmt.Errorf("不支持 i18next 的嵌套 $t()")
	}
	var b strings.Builder
	var params []string
	for i := 0; i < len(s); {
		if m := placeholder.FindStringSubmatch(s[i:]); m != nil {
			name := m[1]
			if !slices.Contains(params, name) {
				params = append(params, name)
			}
			b.WriteString("{" + name + "}")
			i += len(m[0])
			continue
		}
		if strings.HasPrefix(s[i:], "{{") {
			return "", nil, fmt.Errorf("不支持的插值 %q（只支持 {{name}}）", s[i:min(len(s), i+24)])
		}
		switch c := s[i]; c {
		case '\'':
			b.WriteString("''")
		case '{', '}':
			b.WriteString("'" + string(c) + "'")
		default:
			b.WriteByte(c)
		}
		i++
	}
	return b.String(), params, nil
}

// missing 返回 params 里 in 没有的参数。
func missing(params, in []string) []string {
	var out []string
	for _, p := range params {
		if !slices.Contains(in, p) {
			out = append(out, p)
		}
	}
	return out
}

// encode 写出一种语言的 ARB 文件。源语言在每条消息后写 @key：原版的 key 与参数的类型。
func encode(lang string, msgs []message, source bool) []byte {
	var b bytes.Buffer
	b.WriteString("{\n")
	writeKV(&b, "@@locale", lang)
	for _, m := range msgs {
		b.WriteString(",\n")
		writeKV(&b, m.key, m.text)
		if !source || strings.HasPrefix(m.key, "mygo.") {
			continue
		}
		// 参数按在源语言消息里出现的顺序写出，Go 函数的参数也是这个顺序。
		b.WriteString(",\n")
		b.WriteString("  " + quote("@"+m.key) + ": {\"description\": " + quote(m.origin))
		if len(m.params) > 0 {
			b.WriteString(", \"placeholders\": {")
			for i, p := range m.params {
				if i > 0 {
					b.WriteString(", ")
				}
				b.WriteString(quote(p) + ": {\"type\": \"String\"}")
			}
			b.WriteString("}")
		}
		b.WriteString("}")
	}
	b.WriteString("\n}\n")
	return b.Bytes()
}

func writeKV(b *bytes.Buffer, k, v string) {
	b.WriteString("  " + quote(k) + ": " + quote(v))
}

func quote(s string) string { return string(marshal(s)) }

// marshal 写出不转义 HTML 字符的紧凑 JSON；map 的 key 排序，参数的顺序在消息里，不受影响。
func marshal(v any) []byte {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(v); err != nil {
		panic(err)
	}
	return bytes.TrimRight(b.Bytes(), "\n")
}

// Diff 比较转换结果与 dir 中已有的目录，返回不一致的文件（缺失、内容不同、多出来的语言）。
func (r *Result) Diff(dir string) []string {
	var out []string
	names := make([]string, 0, len(r.Files))
	for name := range r.Files {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		got, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil || !bytes.Equal(normalizeEOL(got), r.Files[name]) {
			out = append(out, name)
		}
	}
	existing, _ := filepath.Glob(filepath.Join(dir, "*.json"))
	for _, p := range existing {
		if _, ok := r.Files[filepath.Base(p)]; !ok {
			out = append(out, filepath.Base(p)+"（多余）")
		}
	}
	return out
}

// Write 把转换结果写进 dir，删除不再支持的语言的目录。
func (r *Result) Write(dir string) error {
	existing, _ := filepath.Glob(filepath.Join(dir, "*.json"))
	for _, p := range existing {
		if _, ok := r.Files[filepath.Base(p)]; !ok {
			if err := os.Remove(p); err != nil {
				return err
			}
		}
	}
	for name, data := range r.Files {
		if err := os.WriteFile(filepath.Join(dir, name), data, 0o644); err != nil {
			return err
		}
	}
	return nil
}

func normalizeEOL(b []byte) []byte { return bytes.ReplaceAll(b, []byte("\r\n"), []byte("\n")) }
